function test_wgs_protocol()
%TEST_WGS_PROTOCOL Hardware-free checks for WGS frame construction.

    C = wgs.internal.constants();

    ping = wgs.internal.buildFrame(C.FRAME_COMMAND, uint8(C.CMD_PING));
    assertBytesEqual(ping, uint8([hex2dec("A5"), 1, 1, 0, 0]));

    sync = wgs.internal.buildFrame(C.FRAME_COMMAND, uint8(C.CMD_SYNC));
    assertBytesEqual(sync, uint8([hex2dec("A5"), 1, 1, 0, 1]));

    pointPayload = [
        uint8(C.CMD_POINT_SET), ...
        uint8(C.CHANNEL_1), ...
        wgs.internal.float32le(1.5)
    ];
    pointFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, pointPayload);
    assertBytesEqual(pointFrame, uint8([ ...
        hex2dec("A5"), 1, 6, 0, hex2dec("10"), 1, ...
        0, 0, hex2dec("C0"), hex2dec("3F")]));

    pointNoAckPayload = [
        uint8(C.CMD_POINT_SET_NO_ACK), ...
        uint8(C.CHANNEL_1), ...
        wgs.internal.float32le(1.5)
    ];
    pointNoAckFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, pointNoAckPayload);
    assertBytesEqual(pointNoAckFrame, uint8([ ...
        hex2dec("A5"), 1, 6, 0, hex2dec("12"), 1, ...
        0, 0, hex2dec("C0"), hex2dec("3F")]));

    point2Payload = [
        uint8(C.CMD_POINT2_SET), ...
        wgs.internal.float32le(1.5), ...
        wgs.internal.float32le(2.5)
    ];
    point2Frame = wgs.internal.buildFrame(C.FRAME_COMMAND, point2Payload);
    assertBytesEqual(point2Frame, uint8([ ...
        hex2dec("A5"), 1, 9, 0, hex2dec("11"), ...
        0, 0, hex2dec("C0"), hex2dec("3F"), ...
        0, 0, hex2dec("20"), hex2dec("40")]));

    point2NoAckPayload = [
        uint8(C.CMD_POINT2_SET_NO_ACK), ...
        wgs.internal.float32le(1.5), ...
        wgs.internal.float32le(2.5)
    ];
    point2NoAckFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, point2NoAckPayload);
    assertBytesEqual(point2NoAckFrame, uint8([ ...
        hex2dec("A5"), 1, 9, 0, hex2dec("13"), ...
        0, 0, hex2dec("C0"), hex2dec("3F"), ...
        0, 0, hex2dec("20"), hex2dec("40")]));

    point2NoAckBatch = wgs.internal.buildPoint2NoAckFrames([1.5, 1.25], [2.5, 2.25]);
    expectedPoint2NoAckBatch = uint8([ ...
        hex2dec("A5"), 1, 9, 0, hex2dec("13"), ...
        0, 0, hex2dec("C0"), hex2dec("3F"), ...
        0, 0, hex2dec("20"), hex2dec("40"), ...
        hex2dec("A5"), 1, 9, 0, hex2dec("13"), ...
        0, 0, hex2dec("A0"), hex2dec("3F"), ...
        0, 0, hex2dec("10"), hex2dec("40")]);
    assertBytesEqual(point2NoAckBatch, expectedPoint2NoAckBatch);

    try
        wgs.internal.buildPoint2NoAckFrames([1.0, 2.0], 1.5);
        error("WGS:ExpectedErrorMissing", ...
              "buildPoint2NoAckFrames should reject mismatched vector lengths.");
    catch err
        assert(strcmp(err.identifier, "WGS:BadPoint2Batch"), ...
               "Expected WGS:BadPoint2Batch, got %s.", err.identifier);
    end

    fifoClearFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, uint8(C.CMD_POINT2_FIFO_CLEAR));
    assertBytesEqual(fifoClearFrame, uint8([hex2dec("A5"), 1, 1, 0, hex2dec("14")]));

    fifoAppendPayload = wgs.internal.buildPoint2FifoAppendPayload([1.5, 1.25], [2.5, 2.25]);
    expectedFifoAppendPayload = uint8([ ...
        hex2dec("15"), 2, 0, ...
        0, 0, hex2dec("C0"), hex2dec("3F"), ...
        0, 0, hex2dec("20"), hex2dec("40"), ...
        0, 0, hex2dec("A0"), hex2dec("3F"), ...
        0, 0, hex2dec("10"), hex2dec("40")]);
    assertBytesEqual(fifoAppendPayload, expectedFifoAppendPayload);
    fifoAppendFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, fifoAppendPayload);
    assertBytesEqual(fifoAppendFrame, uint8([ ...
        hex2dec("A5"), 1, hex2dec("13"), 0, expectedFifoAppendPayload]));

    try
        wgs.internal.buildPoint2FifoAppendPayload([1.0, 2.0], 1.5);
        error("WGS:ExpectedErrorMissing", ...
              "buildPoint2FifoAppendPayload should reject mismatched vector lengths.");
    catch err
        assert(strcmp(err.identifier, "WGS:BadPoint2FifoAppend"), ...
               "Expected WGS:BadPoint2FifoAppend, got %s.", err.identifier);
    end

    fifoStartFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, uint8(C.CMD_POINT2_FIFO_START));
    assertBytesEqual(fifoStartFrame, uint8([hex2dec("A5"), 1, 1, 0, hex2dec("16")]));

    fifoStopFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, uint8(C.CMD_POINT2_FIFO_STOP));
    assertBytesEqual(fifoStopFrame, uint8([hex2dec("A5"), 1, 1, 0, hex2dec("17")]));

    pulsePayload = [
        uint8(C.CMD_POINT_PULSE_WIDTH_SET), ...
        wgs.internal.float32le(50.0)
    ];
    pulseFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, pulsePayload);
    assertBytesEqual(pulseFrame, uint8([ ...
        hex2dec("A5"), 1, 5, 0, hex2dec("50"), ...
        0, 0, hex2dec("48"), hex2dec("42")]));

    sequencePayload = [
        uint8(C.CMD_SEQUENCE_SET), ...
        uint8(C.CHANNEL_2), ...
        wgs.internal.uint16le(1000), ...
        repmat(wgs.internal.float32le(1.65), 1, 1000)
    ];
    sequenceFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, sequencePayload);
    assert(sequenceFrame(3) == 164 && sequenceFrame(4) == 15, ...
           "SEQUENCE_SET length bytes should be A4 0F for 1000 samples.");

    timerPayload = [
        uint8(C.CMD_TIMER_SET), ...
        uint8(C.CHANNEL_1), ...
        wgs.internal.float32le(100000)
    ];
    timerFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, timerPayload);
    assertBytesEqual(timerFrame, uint8([ ...
        hex2dec("A5"), 1, 6, 0, hex2dec("40"), 1, ...
        0, 80, hex2dec("C3"), hex2dec("47")]));

    waveformConfigPayload = [
        uint8(C.CMD_WAVEFORM_CONFIG), ...
        uint8(C.CHANNEL_2), ...
        wgs.internal.uint16le(256), ...
        wgs.internal.float32le(12.5)
    ];
    waveformConfigFrame = wgs.internal.buildFrame(C.FRAME_COMMAND, waveformConfigPayload);
    assertBytesEqual(waveformConfigFrame, uint8([ ...
        hex2dec("A5"), 1, 8, 0, hex2dec("30"), 2, ...
        0, 1, 0, 0, hex2dec("48"), hex2dec("41")]));

    disp("WGS protocol frame tests passed.");
end

function assertBytesEqual(actual, expected)
    assert(isequal(uint8(actual), uint8(expected)), ...
           "Expected %s, got %s.", ...
           wgs.internal.bytesToHex(expected), ...
           wgs.internal.bytesToHex(actual));
end
